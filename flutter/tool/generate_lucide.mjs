#!/usr/bin/env node
/**
 * Generates lib/icons/lucide.g.dart from the lucide-react package the web kit uses, so both kits
 * draw the same icons from the same data: `node flutter/tool/generate_lucide.mjs` (from ui/).
 */
import { readdir, writeFile, readFile } from 'node:fs/promises'
import { join } from 'node:path'

const dir = 'node_modules/lucide-react/dist/esm/icons'
const pkg = JSON.parse(await readFile('node_modules/lucide-react/package.json', 'utf8'))
const files = (await readdir(dir)).filter((f) => f.endsWith('.mjs')).sort()
const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase())
const camel = (name) => { const p = pascal(name); return p[0].toLowerCase() + p.slice(1) }
const num = (v) => { const n = Number(v); return Number.isInteger(n) ? `${n}.0` : String(n) }
const str = (v) => `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const seen = new Set()
const aliases = []
const data = []
const widgets = []
for (const file of files) {
  const name = file.replace(/\.mjs$/, '')
  const source = await readFile(join(dir, file), 'utf8')
  const alias = /export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/.exec(source)
  if (alias) {
    aliases.push([name, alias[1]])
    continue
  }
  const { __iconData } = await import(join(process.cwd(), dir, file))
  if (!__iconData) continue
  const id = camel(name)
  if (seen.has(id)) continue
  seen.add(id)
  const elements = __iconData.node.map(([tag, attrs]) => {
    switch (tag) {
      case 'path': return `LucideNodePath(${str(attrs.d)})`
      case 'circle': return `LucideNodeCircle(${num(attrs.cx)}, ${num(attrs.cy)}, ${num(attrs.r)})`
      case 'ellipse': return `LucideNodeEllipse(${num(attrs.cx)}, ${num(attrs.cy)}, ${num(attrs.rx)}, ${num(attrs.ry)})`
      case 'rect': return `LucideNodeRect(${num(attrs.x ?? 0)}, ${num(attrs.y ?? 0)}, ${num(attrs.width)}, ${num(attrs.height)}, ${num(attrs.rx ?? attrs.ry ?? 0)}, ${num(attrs.ry ?? attrs.rx ?? 0)})`
      case 'line': return `LucideNodeLine(${num(attrs.x1)}, ${num(attrs.y1)}, ${num(attrs.x2)}, ${num(attrs.y2)})`
      case 'polyline': return `LucideNodePolyline(${str(attrs.points)})`
      case 'polygon': return `LucideNodePolygon(${str(attrs.points)})`
      default: throw new Error(`${name}: unsupported <${tag}>`)
    }
  })
  data.push(`  static const ${id} = LucideIconData(${str(name)}, [${elements.join(', ')}]);`)
  widgets.push(`/// Lucide \`${name}\` (the web kit's \`Lucide${pascal(name)}\`).\nclass Lucide${pascal(name)} extends LucideIcon {\n  const Lucide${pascal(name)}({super.key, super.size, super.color, super.strokeWidth, super.semanticLabel}) : super(LucideIcons.${id});\n}`)
}

// Old names lucide-react still exports (trash-2 → trash): same data, same widget name as React.
for (const [name, target] of aliases) {
  const id = camel(name)
  if (seen.has(id) || !seen.has(camel(target))) continue
  seen.add(id)
  data.push(`  static const ${id} = ${camel(target)};`)
  widgets.push(`/// Lucide \`${name}\`, another name for \`${target}\` (the web kit's \`Lucide${pascal(name)}\`).\nclass Lucide${pascal(name)} extends LucideIcon {\n  const Lucide${pascal(name)}({super.key, super.size, super.color, super.strokeWidth, super.semanticLabel}) : super(LucideIcons.${camel(target)});\n}`)
}

const out = `// GENERATED by tool/generate_lucide.mjs from lucide-react ${pkg.version} (ISC). Do not edit.
// ignore_for_file: public_member_api_docs

import 'lucide.dart';

/// Every Lucide icon, by the same name lucide-react uses.
abstract final class LucideIcons {
${data.join('\n')}
}

${widgets.join('\n\n')}
`
await writeFile('flutter/lib/icons/lucide.g.dart', out)
console.log(`${data.length - aliases.length} icons and ${aliases.length} aliases from lucide-react ${pkg.version}`)
