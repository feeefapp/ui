// Copies the docs' Dart examples (docs/content/**/examples/*.dart) into the gallery and writes a
// registry, so `?example=components/button/01-variants` renders the same example the docs show.
// Run: node flutter/tool/sync_docs_examples.mjs  (output is generated and gitignored)
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ui = fileURLToPath(new URL('../../', import.meta.url))
const content = join(ui, 'docs/content')
const out = join(ui, 'flutter/example/lib/docs_examples')

const found = []
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) walk(path)
    else if (name.endsWith('.dart') && dir.endsWith('/examples')) found.push(path)
  }
}
walk(content)

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
const imports = []
const entries = []
found.forEach((path, i) => {
  // components/button/examples/01-variants.dart → components/button/01-variants
  const id = relative(content, path).replace('/examples/', '/').replace(/\.dart$/, '')
  const source = readFileSync(path, 'utf8')
  const widget = source.match(/^class (\w+) extends (?:StatelessWidget|StatefulWidget)/m)?.[1]
  if (!widget) throw new Error(`${id}: no public widget class`)
  const file = `${id.replace(/[^a-z0-9]+/gi, '_')}.dart`
  writeFileSync(join(out, file), source)
  imports.push(`import '${file}' as e${i};`)
  entries.push(`  '${id}': () => e${i}.${widget}(),`)
})
writeFileSync(
  join(out, 'registry.dart'),
  `// Generated by flutter/tool/sync_docs_examples.mjs. Do not edit.
import 'package:flutter/widgets.dart';

${imports.join('\n')}

final Map<String, Widget Function()> docsExamples = {
${entries.join('\n')}
};
`
)
console.log(`${found.length} examples → ${relative(ui, out)}`)
