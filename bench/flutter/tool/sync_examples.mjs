// Copies the docs' Dart examples of the benched pages into bench/flutter/lib/examples and writes a
// registry grouped by page (same id scheme as flutter/tool/sync_docs_examples.mjs, which writes
// into the gallery; this one leaves the gallery alone). Output is generated and gitignored.
//   node bench/flutter/tool/sync_examples.mjs components/glass-container,components/actions-bar,…
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ui = fileURLToPath(new URL('../../../', import.meta.url))
const content = join(ui, 'docs/content')
const out = join(ui, 'bench/flutter/lib/examples')
const pages = (process.argv[2] ?? '').split(',').filter(Boolean)

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
const imports = []
const groups = []
let i = 0
for (const page of pages) {
  const dir = join(content, page, 'examples')
  const entries = []
  if (existsSync(dir))
    for (const name of readdirSync(dir).sort().filter((n) => n.endsWith('.dart'))) {
      const id = `${page}/${name.replace(/\.dart$/, '')}`
      const source = readFileSync(join(dir, name), 'utf8')
      const widget = source.match(/^class ([A-Z]\w*) extends (?:StatelessWidget|StatefulWidget)/m)?.[1]
      if (!widget) throw new Error(`${id}: no public widget class`)
      const file = `${id.replace(/[^a-z0-9]+/gi, '_')}.dart`
      writeFileSync(join(out, file), source)
      imports.push(`import '${file}' as e${i};`)
      entries.push(`    ('${id}', () => e${i}.${widget}()),`)
      i++
    }
  groups.push(`  '${page}': [\n${entries.join('\n')}\n  ],`)
}
writeFileSync(
  join(out, 'registry.dart'),
  `// Generated by bench/flutter/tool/sync_examples.mjs. Do not edit.
import 'package:flutter/widgets.dart';

${imports.join('\n')}

/// Page → its docs examples, in docs order.
final Map<String, List<(String, Widget Function())>> benchPages = {
${groups.join('\n')}
};
`
)
console.log(`${i} examples from ${pages.length} pages → bench/flutter/lib/examples`)
